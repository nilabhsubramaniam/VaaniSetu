/**
 * Real India geography for the hero's map scene (`india-map-scene.ts`) —
 * unlike the previous, now-removed hero (docs/DECISIONS.md ADR-019,
 * dropped in commit 624f0ed), which used a random, explicitly
 * "non-geographic/conceptual" sphere. This is the actual country outline.
 *
 * Source: `datameet/maps`, `Country/india-composite.geojson`
 * (https://github.com/datameet/maps, MIT license) — the mainland
 * polygon's outer ring (242,146 raw points: full coastline + land
 * border combined). A first attempt used that same repo's
 * `india-land-simplified.geojson`, which turned out to be a *land
 * border only* line (no coastline, missing all of South India,
 * lat range 21.9°-37.1°) — rejected once that was noticed by checking
 * the actual bounding box against known geography (Kanyakumari is at
 * ~8°N).
 *
 * Processing (one-time, offline — this file is the checked-in result,
 * not something computed at runtime):
 *  1. Extracted the largest ring from the MultiPolygon (the mainland).
 *  2. Simplified by dropping points closer than 0.3° to the previous
 *     kept point (raw 242,146 -> 392 points) — a plain nearest-distance
 *     filter, not a proper Douglas-Peucker, but sufficient for a
 *     decorative glow outline at hero-image sizes.
 *  3. Applied a `cos(mean latitude)` correction to longitude (mean
 *     latitude ~22.5°) so the outline's aspect ratio isn't stretched by
 *     the equirectangular lon/lat degrees themselves being unequal
 *     widths at this latitude.
 *  4. Centered and scaled into a compact unit space (roughly
 *     [-1.55, 1.55] x [-1.7, 1.7]) convenient for Three.js — these are
 *     NOT real lat/lon or any standard projection's coordinates.
 *
 * `INDIA_REGION_POSITIONS` (the hero's 6 region cards, `hero-region.
 * model.ts`) are projected through the exact same formula from each
 * region's state-capital coordinates (Guwahati, Amritsar, Kolkata,
 * Srinagar, Chennai, Panaji), so they land in the right place relative
 * to the outline above.
 */

